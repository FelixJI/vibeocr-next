def _standalone_error_schema(openapi: dict) -> str:
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://vibeocr/protocol/v2/errors.schema.json",
        "title": "VibeOCR v2 Error Response",
        **openapi["components"]["schemas"]["Error"],
    }
    return json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


def _outputs() -> dict[Path, str]:
    capabilities = _read("capabilities.json")["capabilities"]
    bootstrap = _read("bootstrap.schema.json")
    errors = _read("errors.json")
    openapi = _read("openapi.yaml")
    runtime_host = _read("runtime-host.schema.json")
    runtime_host_components = {"components": {"schemas": runtime_host["$defs"]}}
    return {
        V2 / "schemas/errors.schema.json": _standalone_error_schema(openapi),
        V2 / "generated/capabilities.py": _python(capabilities, bootstrap),
        V2 / "generated/operations.py": _python_operations(openapi),
        V2 / "generated/error_codes.py": _python_errors(errors),
        V2 / "generated/models.py": _python_models(bootstrap),
        V2 / "generated/server.py": _python_server_contracts(openapi),
        V2 / "generated/wire_types.py": _python_wire_types(openapi),
        V2 / "generated/__init__.py": _generated_init(),
        V2 / "generated/RuntimeProtocol.g.cs": _csharp(
            capabilities,
            bootstrap,
            errors,
            openapi,
        ),
        V2 / "generated/RuntimeWireTypes.g.cs": _csharp_wire_types(openapi),
        V2 / "generated/runtime_host_types.py": _python_wire_types(
            runtime_host_components
        ),
        V2 / "generated/RuntimeHostWireTypes.g.cs": _csharp_wire_types(
            runtime_host_components
        ).replace(
            "namespace VibeOCR.Runtime.Contracts.Generated.Wire;",
            "namespace VibeOCR.Runtime.Contracts.Generated.Host;",
        ),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale: list[Path] = []
    for path, content in _outputs().items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if stale and args.check:
        print("Generated runtime protocol files are stale:")
        print("\n".join(str(path.relative_to(ROOT)) for path in stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
