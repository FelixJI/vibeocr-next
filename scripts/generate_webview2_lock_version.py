"""#321 F1：从 webview2-runtime.lock.json 生成锁版本 C# 常量（唯一版本源）。"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
_LOCK = _REPO_ROOT / "config" / "runtime" / "webview2-runtime.lock.json"
_VERSION_PATTERN = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$")


def locked_runtime_version(lock_path: Path = _LOCK) -> str:
    lock = json.loads(lock_path.read_text(encoding="utf-8"))
    version = lock.get("version")
    if not isinstance(version, str) or not _VERSION_PATTERN.match(version):
        raise ValueError(
            f"webview2-runtime.lock.json version must be four-part numeric: {version!r}"
        )
    return version


def render() -> str:
    version = locked_runtime_version()
    return (
        "// <auto-generated from config/runtime/webview2-runtime.lock.json />\n"
        "// Rebuild regenerates this file; do not edit or pin the version here.\n"
        "namespace VibeOCR.ProductLayout;\n"
        "\n"
        "internal static class WebView2LockVersion\n"
        "{\n"
        f'    internal const string LockedRuntimeVersion = "{version}";\n'
        "}\n"
    )


def generate(output: Path, lock_path: Path = _LOCK) -> Path:
    content = render()
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text(encoding="utf-8") == content:
        return output
    output.write_text(content, encoding="utf-8", newline="\n")
    return output


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        # 纯比较：不向受检目录写任何文件。
        if (
            not args.output.is_file()
            or args.output.read_text(encoding="utf-8") != render()
        ):
            raise SystemExit("generated WebView2 lock version is stale")
        return 0
    generate(args.output)
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
