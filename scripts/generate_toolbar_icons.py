"""从本地图标源生成 WinUI/Web 共用的路径目录及专用效果图形。"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "src/dotnet/VibeOCR.App"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads(
        (ROOT / "assets/icons/tabler-toolbar.json").read_text("utf-8-sig")
    )
    assert catalog["size"] == 24 and catalog["license"] == "MIT"
    assert 2 <= catalog["strokeWidth"] <= 2.5
    icons = catalog["icons"]
    assert icons and "textRecognition" in icons
    effects = json.loads(
        (ROOT / "assets/icons/toolbar-effects.json").read_text("utf-8")
    )
    assert effects["size"] == catalog["size"]
    effect_icons = effects["icons"]
    assert set(effect_icons) == {"mosaic", "blur", "reselect", "hand"}
    for key, icon in effect_icons.items():
        assert key in icons and icon["layers"]
        for layer in icon["layers"]:
            assert 0 < layer["opacity"] <= 1
            assert layer["path"].startswith("M")
            assert all(
                char in "MmZzLlHhVvCcSsQqTtAa0123456789.,-+ eE"
                for char in layer["path"]
            )
        icons[key] = {"path": " ".join(layer["path"] for layer in icon["layers"])}
    native = [
        "// Generated by scripts/generate_toolbar_icons.py; do not edit.",
        "namespace VibeOCR.App.Features.Recognition;",
        "",
        "internal static partial class ScreenshotToolbarIcons",
        "{",
        f"  internal const double IconSize = {catalog['size']};",
        f"  internal const double StrokeWidth = {catalog['strokeWidth']};",
        "",
        "  private static readonly IReadOnlyDictionary<string, string> Paths =",
        "    new Dictionary<string, string>(StringComparer.Ordinal)",
        "    {",
    ]
    web = [
        "// Generated by scripts/generate_toolbar_icons.py; do not edit.",
        f"export const toolbarIconSize = {catalog['size']};",
        f"export const toolbarIconStrokeWidth = {catalog['strokeWidth']};",
        "export const toolbarIconData = {",
    ]
    for key, icon in icons.items():
        assert key.isidentifier() and icon["path"].startswith("M")
        path = icon["path"]
        assert all(char in "MmZzLlHhVvCcSsQqTtAa0123456789.,-+ eE" for char in path)
        native.append(f'      ["{key}"] = "{path}",')
        web.extend(
            [
                f"  {key}: {{",
                f'    path: "{path}",',
                "  },",
            ]
        )
    native.extend(
        [
            "    };",
            "",
            "  internal sealed record IconLayer(string Path, double Opacity, bool Stroke, bool Dashed);",
            "  internal static readonly IReadOnlyDictionary<string, IconLayer[]> EffectLayers =",
            "    new Dictionary<string, IconLayer[]>(StringComparer.Ordinal)",
            "    {",
        ]
    )
    web.extend(
        [
            "} as const;",
            "",
            "export type ToolbarIconName = keyof typeof toolbarIconData;",
            "",
            "export const toolbarIconEffects: Partial<",
            "  Record<",
            "    ToolbarIconName,",
            "    readonly {",
            "      path: string;",
            "      opacity: number;",
            "      stroke: boolean;",
            "      dashed: boolean;",
            "    }[]",
            "  >",
            "> = {",
        ]
    )
    for key, icon in effect_icons.items():
        native.extend([f'      ["{key}"] =', "      ["])
        web.append(f"  {key}: [")
        for layer in icon["layers"]:
            stroke = str(layer.get("stroke", False)).lower()
            dashed = str(layer.get("dashed", False)).lower()
            native.append(
                f'        new("{layer["path"]}", {layer["opacity"]}, {stroke}, {dashed}),'
            )
            web.extend(
                [
                    "    {",
                    f'      path: "{layer["path"]}",',
                    f"      opacity: {layer['opacity']},",
                    f"      stroke: {stroke},",
                    f"      dashed: {dashed},",
                    "    },",
                ]
            )
        native.append("      ],")
        web.append("  ],")
    native.extend(["    };", "}"])
    web.append("};")
    outputs = {
        APP / "Features/Recognition/ScreenshotToolbarIconData.g.cs": native,
        APP / "WebAssets/src/components/toolbarIconData.ts": web,
    }
    stale = []
    for path, lines in outputs.items():
        expected = "\n".join(lines) + "\n"
        if args.check:
            if not path.exists() or path.read_text("utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        print("Toolbar icon data is stale: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
